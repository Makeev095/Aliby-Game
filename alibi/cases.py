def assign_roles(player_count: int):
    if player_count < 3 or player_count > 6:
        raise ValueError("need 3 to 6 players")
    roles = sorted(CASE["roles"], key=lambda role: role["priority"])
    thief = roles[0]
    innocents = roles[1:]
    chosen = [thief] + innocents[: player_count - 1]
    return chosen
